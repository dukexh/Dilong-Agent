// Development-only: copy web derivatives and compute the existing app's image
// features once, so visitors do not download/decode the entire library.
const fs=require('node:fs'),path=require('node:path'),http=require('node:http');
const {chromium}=require('playwright');
const root=path.resolve(__dirname,'..');
async function main(){
  const input=path.resolve(process.argv[2]),rows=JSON.parse(fs.readFileSync(path.join(input,'manifest.json'),'utf8'));
  const out=path.join(root,'public-textures');
  if(fs.existsSync(out))throw Error('Refusing to overwrite '+out);
  const server=http.createServer((req,res)=>{const file=path.resolve(root,'.'+new URL(req.url,'http://localhost').pathname);if(!file.startsWith(root+path.sep)){res.writeHead(404);res.end();return}fs.readFile(file,(e,b)=>{res.statusCode=e?404:200;res.setHeader('Content-Type',({'.html':'text/html','.js':'text/javascript','.webp':'image/webp','.css':'text/css'})[path.extname(file)]||'application/octet-stream');res.end(e?'':b)})});
  await new Promise(r=>server.listen(0,'127.0.0.1',r));
  const browser=await chromium.launch({channel:'chrome',headless:true});
  try{
    const page=await browser.newPage();await page.goto('http://127.0.0.1:'+server.address().port+'/index.html');await page.evaluate(()=>DilongStage1.ready);
    const existing=new Set(await page.evaluate(()=>DilongStage1.base.map(r=>r.assetId)));
    const selected=rows.filter(r=>!(r.source==='polyhaven'&&existing.has(r.source_id)));
    fs.mkdirSync(path.join(out,'images'),{recursive:true});fs.mkdirSync(path.join(out,'thumbnails'));
    for(const r of selected){fs.copyFileSync(path.join(input,r.imageUrl),path.join(out,'images',r.id+'.webp'));fs.copyFileSync(path.join(input,r.thumbnail),path.join(out,'thumbnails',r.id+'.webp'))}
    const records=[];
    for(let i=0;i<selected.length;i+=16){
      const batch=selected.slice(i,i+16);
      const features=await page.evaluate(async batch=>Promise.all(batch.map(async r=>({id:r.id,...await DilongStage1.analyze('public-textures/images/'+r.id+'.webp')}))),batch);
      for(let j=0;j<batch.length;j++){const r=batch[j],f=features[j];records.push({id:'TX-'+r.id,assetId:r.id,name:r.name,category:r.category,tags:r.tags,source:r.source,sourceId:r.source_id,imageUrl:'./public-textures/images/'+r.id+'.webp',thumbnailUrl:'./public-textures/thumbnails/'+r.id+'.webp',width:r.width,height:r.height,sourceUrl:r.source_url,license:r.license,licenseUrl:r.license_url,features:{averageRgb:f.averageRgb,brightness:f.brightness,textureDensity:f.textureDensity}})}
      if(i%160===0)console.log('FEATURES '+Math.min(i+16,selected.length)+'/'+selected.length);
    }
    const data={version:1,records};
    fs.writeFileSync(path.join(out,'catalog.js'),'// Generated by scripts/build-public-textures.cjs; features use the app image algorithm.\nwindow.DilongPublicTextureData='+JSON.stringify(data)+';\n');
    fs.writeFileSync(path.join(out,'sources.json'),JSON.stringify(Object.fromEntries(rows.map(r=>[r.source,{license:r.license,licenseUrl:r.license_url}])),null,2));
    console.log(JSON.stringify({input:rows.length,existingSkipped:rows.length-records.length,added:records.length}));
  }finally{await browser.close();await new Promise(r=>server.close(r))}
}
main().catch(e=>{console.error(e);process.exitCode=1});
